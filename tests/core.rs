#[test]
fn offset_name_labels_exclude_distant_vertical_watermark() {
    let mut input = page(&[
        ("销", 300.0, 10.0),
        ("售", 300.0, 20.0),
        ("名称:", 25.0, 22.8),
        ("名称:", 320.0, 22.8),
        ("杭州电子科技大学", 53.0, 20.0),
        ("深圳市测试电子有限公司", 348.0, 20.0),
        ("数", 580.0, 20.0),
    ]);
    for glyph in input.glyphs.iter_mut().filter(|g| (g.y - 22.8).abs() < 0.1) {
        glyph.height = if glyph.ch == ':' { 1.0 } else { 5.0 };
    }
    assert_eq!(
        from_pages(&[input]).seller.value().map(String::as_str),
        Some("深圳市测试电子有限公司")
    );
}

#[cfg(windows)]
#[test]
#[ignore = "requires PAYMERGE_TEST_FIXTURES generated by server acceptance"]
fn locked_output_keeps_original_and_removes_partial_file() {
    use std::os::windows::fs::OpenOptionsExt;
    let root = std::path::PathBuf::from(
        std::env::var_os("PAYMERGE_TEST_FIXTURES").expect("fixture directory"),
    );
    let output = root.join("windows-locked.pdf");
    std::fs::write(&output, b"original locked content").unwrap();
    let before: Vec<_> = std::fs::read_dir(&root)
        .unwrap()
        .map(|p| p.unwrap().file_name())
        .collect();
    let held = std::fs::OpenOptions::new()
        .read(true)
        .write(true)
        .share_mode(0)
        .open(&output)
        .unwrap();
    let result = paymerge_pdf::merge::merge_invoice(
        &root.join("invoice-1.pdf"),
        &root.join("购买 记录.png"),
        &root.join("支付 记录.png"),
        &output,
        true,
    );
    assert!(result.is_err());
    drop(held);
    assert_eq!(std::fs::read(&output).unwrap(), b"original locked content");
    let after: Vec<_> = std::fs::read_dir(&root)
        .unwrap()
        .map(|p| p.unwrap().file_name())
        .collect();
    assert_eq!(before, after);
    std::fs::remove_file(output).unwrap();
}

#[test]
fn no_text_requires_valid_manual_fields_and_confirmation() {
    let data = from_pages(&[PageText { glyphs: vec![] }]);
    let mut review = Review::from_invoice(&data);
    review.number = "00000000000000001234".into();
    review.amount = "12.30".into();
    assert!(review.validated(&data).is_err());
    review.confirmed = true;
    assert_eq!(
        review.validated(&data).unwrap(),
        (review.number.clone(), Money(1230))
    );
    let replacement = Review::from_invoice(&data);
    assert!(
        replacement.number.is_empty() && replacement.amount.is_empty() && !replacement.confirmed
    );
}

