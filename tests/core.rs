#[test]
fn existing_config_relative_output_and_duplicate_names() {
    let temp = tempfile::tempdir().unwrap();
    let app = temp.path();
    std::fs::create_dir(app.join("输出 空间")).unwrap();
    let mut config = Config {
        name: "测试者".into(),
        group: "实验A组".into(),
        ..Default::default()
    };
    config.set_output("输出 空间", app);
    config.save(app).unwrap();
    let mut loaded = Config::load(app).unwrap();
    assert_eq!(loaded.name, "测试者");
    loaded.output_path_absolute = "不存在的绝对目录".into();
    assert_eq!(loaded.output_directory(app).unwrap(), app.join("输出 空间"));
    let output = app.join("测试_A组_12.30_1234.pdf");
    std::fs::write(&output, b"original").unwrap();
    let first = numbered_path(&output);
    assert_eq!(first.file_name().unwrap(), "测试_A组_12.30_1234_1.pdf");
    std::fs::write(first, b"first").unwrap();
    assert_eq!(
        numbered_path(&output).file_name().unwrap(),
        "测试_A组_12.30_1234_2.pdf"
    );
    loaded.output_path_relative = "also missing".into();
    assert!(loaded.output_directory(app).is_err());
    assert_eq!(std::fs::read(output).unwrap(), b"original");
}

