use paymerge_pdf::{
    config::{Config, numbered_path},
    extract::{Glyph, PageText, from_pages},
    model::{Money, Recognition, Review, filename},
};

fn row(text: &str, x: f32, y: f32) -> Vec<Glyph> {
    text.chars()
        .enumerate()
        .map(|(i, ch)| Glyph {
            ch,
            x: x + i as f32 * 7.0,
            y,
            width: 7.0,
            height: 10.0,
        })
        .collect()
}

fn page(rows: &[(&str, f32, f32)]) -> PageText {
    PageText {
        glyphs: rows
            .iter()
            .flat_map(|(text, x, y)| row(text, *x, *y))
            .collect(),
    }
}

#[test]
fn money_is_exact_and_formats_existing_names() {
    assert_eq!(Money::parse("￥１,２３４．５０"), Some(Money(123450)));
    assert_eq!(Money::parse("1.15"), Some(Money(115)));
    assert_eq!(Money::parse("1.005"), None);
    assert_eq!(
        filename("测试", "A组", Money(10000), "00000000000000001234").unwrap(),
        "测试_A组_100_1234.pdf"
    );
    assert_eq!(Money(-125).to_string(), "-1.25");
}

#[test]
fn fields_follow_geometry_instead_of_content_stream_order() {
    let mut p = page(&[
        ("发 票 号 码：", 250.0, 20.0),
        ("00000000000000001234", 360.0, 20.0),
        ("开票日期：2026年11月20日", 250.0, 42.0),
        ("价税合计（小写）￥1,234.50", 20.0, 180.0),
        ("无关商品金额 ¥9999.00", 20.0, 130.0),
    ]);
    p.glyphs.reverse();
    for glyph in p.glyphs.iter_mut().filter(|g| g.ch == '.' || g.ch == ',') {
        glyph.height = 1.0;
    }
    let data = from_pages(&[p]);
    assert_eq!(
        data.number.value().map(String::as_str),
        Some("00000000000000001234")
    );
    assert_eq!(data.amount.value(), Some(&Money(123450)));
    assert_eq!(data.date.value().map(String::as_str), Some("2026-11-20"));
}

#[test]
fn unlabeled_largest_amount_is_never_assumed_to_be_total() {
    let data = from_pages(&[page(&[
        ("商品单价 ¥500.00", 10.0, 20.0),
        ("实付 ¥100.00", 10.0, 50.0),
    ])]);
    assert_eq!(data.amount, Recognition::Missing);
}

#[test]
fn different_totals_require_review_but_repeated_totals_do_not() {
    let a = page(&[("价税合计（小写）¥12.30", 10.0, 50.0)]);
    let b = page(&[("价税合计（小写）¥45.60", 10.0, 50.0)]);
    assert!(matches!(
        from_pages(&[a.clone(), b]).amount,
        Recognition::Conflict(_)
    ));
    assert_eq!(
        from_pages(&[a.clone(), a]).amount.value(),
        Some(&Money(1230))
    );
}

#[test]
